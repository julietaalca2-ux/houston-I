const fs = require('fs');
const vm = require('vm');
const path = require('path');
const root = path.resolve(__dirname, '..', '..');
const context = { console, Map, Set, Number, Array, Object, Error, TypeError, Math };
context.window = context; vm.createContext(context);
['engine/ecs/Entity.js','engine/ecs/Component.js','engine/ecs/System.js','engine/ecs/ECSWorld.js','engine/physics/PhysicsSystem.js','engine/physics/PhysicsFactory.js'].forEach((file) => vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), context, { filename: file }));
const ns = context.CiudadEngine; const world = new ns.ECSWorld();
const physics = new ns.PhysicsSystem({ gravity: -10, groundY: 0 }); world.addSystem(physics);
const factory = new ns.PhysicsFactory(world);
const body = factory.createBody({ name: 'Player', x: 0, y: 2, halfExtents: { x: .5, y: .5, z: .5 } });
world.update(.5, .5);
const transform = world.getComponent(body, 'Transform'); const rb = world.getComponent(body, 'RigidBody');
if (!(transform.y < 2 && rb.velocity.y < 0)) throw new Error('Gravity integration failed');
for (let i = 0; i < 60; i++) world.update(1/60, .5 + (i+1)/60);
if (Math.abs(transform.y - .5) > .001 || !rb.grounded || rb.velocity.y !== 0) throw new Error('Ground collision failed');
factory.createStaticBox({ x: 2, y: .5, z: 0, halfExtents: { x: .5, y: .5, z: .5 } });
const wallBody = factory.createBody({ x: 1.2, y: .5, z: 0, useGravity: false, velocity: { x: 2, y: 0, z: 0 } });
world.update(.1, 2);
if (world.getComponent(wallBody, 'Transform').x > 1.001) throw new Error('Static AABB collision failed');
if (physics.lastStats.bodies !== 2) throw new Error('Physics diagnostics failed');
console.log('PhysicsSystem smoke test: PASS');
