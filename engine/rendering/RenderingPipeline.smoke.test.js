const assert = require('assert');
global.window = global;
let pixelRatio = 0;
global.THREE = { PCFSoftShadowMap: 2, ACESFilmicToneMapping: 4, SRGBColorSpace: 'srgb' };
require('./RenderingPipeline.js');
const pipeline = new global.CiudadEngine.RenderingPipeline({ quality: 'medium' });
const scene = { traverse(fn) { fn({ isDirectionalLight: true, shadow: { mapSize: { set(x,y) { this.x=x; this.y=y; } } } }); } };
const renderer = { shadowMap: {}, setPixelRatio(v) { pixelRatio = v; } };
pipeline.attach({ renderer, scene, camera: {} });
assert.strictEqual(renderer.shadowMap.enabled, true);
assert.strictEqual(renderer.toneMapping, 4);
assert.strictEqual(pixelRatio, 1);
assert.strictEqual(pipeline.getDiagnostics().quality, 'medium');
pipeline.setQuality('low');
assert.strictEqual(renderer.shadowMap.enabled, false);
assert.strictEqual(pipeline.getDiagnostics().shadowMapSize, 512);
assert.throws(() => pipeline.setQuality('cinematic'), /Unknown rendering quality/);
pipeline.dispose();
console.log('RenderingPipeline smoke test: PASS');
